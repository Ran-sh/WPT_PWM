def main():
    # 自测: CRC32("1234") == 0x9BE3E0A3 (STM32 CRC32_Compute 预计算值)
    assert compute_crc32(b"1234") == 0x9BE3E0A3, \
        "CRC32 自测失败! Python zlib.crc32 与 STM32 CRC32_Compute 不一致"
    print("[OK] CRC32 自测通过: CRC32('1234') = 0x9BE3E0A3")

    # 加载宋体 16px
    font_paths = [
        os.path.expandvars(r"%SystemRoot%\Fonts\simsun.ttc"),
        "/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    ]
    font = None
    for fp in font_paths:
        if os.path.exists(fp): font = ImageFont.truetype(fp, 16); print(f"[OK] 加载字体: {fp}"); break
    if font is None: raise RuntimeError("未找到 simsun.ttc 或 NotoSansCJK, 请安装中文字体")

    # ASCII
    print("[..] 渲染 ASCII 95 字...")
    ascii_data = render_ascii(font)
    assert len(ascii_data) == ASCII_COUNT * 16, f"ASCII 大小异常: {len(ascii_data)}"

    # CJK
    print(f"[..] 渲染 GB2312 一级汉字 {CJK_COUNT} 字...")
    cjk_codes = list(range(CJK_START, CJK_END + 1))
    cjk_index, cjk_glyph = render_cjk(font, cjk_codes)
    assert len(cjk_index) == CJK_COUNT * 4, f"CJK Index 大小异常: {len(cjk_index)}"
    assert len(cjk_glyph) == CJK_COUNT * 32, f"CJK Data 大小异常: {len(cjk_glyph)}"

    # 自测: "一"(U+4E00) 渲染结果与现有 CN_FONT_16X16[0] 比对 (可选, 仅告警)
    # CN_FONT_16X16[0] 前 2B = 0x00,0x00 (第一行全空)
    # PIL 渲染的 "一"(U+4E00) 中, 一 是横线在第7~8行, 前6行为空
    # 如果 first_row 非空, 说明 bit_reverse 或位序映射有误
    idx0_uc, idx0_off = struct.unpack_from('<HH', cjk_index, 0)
    first_row_lo = cjk_glyph[idx0_off]
    first_row_hi = cjk_glyph[idx0_off + 1]
    if idx0_uc == CJK_START:
        print(f"[OK] CJK Index[0] Unicode=U+{idx0_uc:04X} ('一'), offset={idx0_off}")
        if first_row_lo == 0x00 and first_row_hi == 0x00:
            print("[OK] '一' 第0行全空 → 位序映射正确 (一 的横线在第7行)")
        else:
            print(f"[WARN] '一' Row0: lo=0x{first_row_lo:02X} hi=0x{first_row_hi:02X} "
                  "→ 位序可能需 bit_reverse 调整, 请与 TFT_Font_Data.h CN_FONT_16X16[0] 比对")

    # 组装
    print("[..] 组装 2MB 镜像...")
    img, hdr = assemble_font_image(ascii_data, cjk_index, cjk_glyph)
    assert len(img) == FLASH_SIZE, f"镜像大小异常: {len(img)} (期望 {FLASH_SIZE})"

    # 输出
    with open(FONT_DATA_BIN, 'wb') as f: f.write(img)
    print(f"[OK] 生成 {FONT_DATA_BIN} ({len(img)} 字节 = 2MB)")
    print(f"     Header:    0x000000 ({len(hdr)}B)")
    print(f"     ASCII:     0x{OFF_ASCII:06X} ({len(ascii_data)}B)")
    print(f"     Icons:     0x{align_to(OFF_ASCII + len(ascii_data), ALIGN):06X}")
    print(f"     CJK Index: 0x{align_to(OFF_ASCII + len(ascii_data) + 1832 + 1728 + 255, ALIGN):06X} "
          f"({len(cjk_index)}B, {CJK_COUNT} 条)")
    print(f"     CJK Data:  0x{align_to(OFF_ASCII + len(ascii_data) + 1832 + 1728 + 255 + len(cjk_index) + 255, ALIGN):06X} "
          f"({len(cjk_glyph)}B)")
    print(f"     CRC32:     0x{struct.unpack_from('<I', hdr, 0x08)[0]:08X}")
    sector_cnt = (total_size + 4095) // 4096
    print(f"     擦除扇区:  {sector_cnt} 个 (0x000000~0x{sector_cnt * 4096:06X})")


if __name__ == '__main__':
    main()
